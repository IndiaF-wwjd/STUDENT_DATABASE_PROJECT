	FROM STUDENTS;
-- Count how many courses each department offers.
SELECT DEPT_ID, COUNT(*) AS COURSE_COUNT
	FROM COURSE
		GROUP BY DEPT_ID;
-- Calculate the average credit hours of all courses.
SELECT AVG(CREDIT_HOURS) AS AVERAGE_CREDIT_HOURS
	FROM COURSE;
-- Find the department that offers the most courses.
SELECT DEPT_ID, COUNT(*) AS COURSE_COUNT
	FROM COURSE
	GROUP BY DEPT_ID
	ORDER BY COURSE_COUNT DESC
	LIMIT 1;
