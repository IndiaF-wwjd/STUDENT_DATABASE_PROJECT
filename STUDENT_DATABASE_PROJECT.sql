-- Find all students enrolled in courses worth more than 3 credit hours.
SELECT STUDENTS.FIRST_NAME, STUDENTS.LAST_NAME, COURSE.COURSE_NAME, COURSE.CREDIT_HOURS
	FROM STUDENTS
	JOIN ENROLLMENT
	ON STUDENTS.STUDENT_ID = ENROLLMENT.STUDENT_ID
	JOIN COURSE
	ON ENROLLMENT.COURSE_ID = COURSE.COURSE_ID
		WHERE COURSE.CREDIT_HOURS > 3;
-- Find the instructor(s) teaching the course with the highest number of credit hours.
SELECT FIRST_NAME, LAST_NAME
	FROM INSTRUCTOR
		WHERE INSTRUCTOR_ID IN (SELECT INSTRUCTOR_ID
									FROM COURSE
										WHERE CREDIT_HOURS =
											(SELECT MAX(CREDIT_HOURS)
												FROM COURSE));
-- Create a view that displays each students full name, course name, semester, and grade. STUDENT, COURSE, ENROLLMENT
CREATE VIEW STDT (FN,CN,S,G) AS
	SELECT CONCAT(STUDENTS.FIRST_NAME, ' ', STUDENTS.LAST_NAME), COURSE.COURSE_NAME, ENROLLMENT.SEMESTER, ENROLLMENT.GRADE
		FROM STUDENTS
        JOIN ENROLLMENT
		ON STUDENTS.STUDENT_ID = ENROLLMENT.STUDENT_ID
        JOIN COURSE
        ON ENROLLMENT.COURSE_ID = COURSE.COURSE_ID;
